"""Tests for browser detection used by the extension install guide."""

import os
import sys

sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__))))

from hdm.utils.browsers import bundled_extension_dir, detect_browsers


def test_detected_browsers_have_valid_paths():
    for browser in detect_browsers():
        assert os.path.exists(browser.exe_path)
        assert browser.kind in ("chromium", "firefox")
        if browser.kind == "chromium":
            assert os.path.isdir(browser.user_data_dir)
        else:
            assert os.path.exists(browser.profiles_ini)
        assert browser.management_page


def test_management_pages_match_kind():
    for browser in detect_browsers():
        if browser.kind == "firefox":
            assert browser.management_page.startswith("about:debugging")
        else:
            assert browser.management_page.endswith("://extensions")


def test_bundled_extension_folders_exist():
    chromium = bundled_extension_dir("chromium")
    assert chromium.endswith("extension")
    assert os.path.isfile(os.path.join(chromium, "manifest.json"))

    # The Firefox bundle is generated by build_extension.py; skip when absent.
    firefox = bundled_extension_dir("firefox")
    if firefox:
        assert firefox.endswith("extension-firefox")
        assert os.path.isfile(os.path.join(firefox, "manifest.json"))
